import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { defineConfig, type Plugin, type ResolvedConfig } from 'vite';
import react from '@vitejs/plugin-react';

const sharedDir = fileURLToPath(new URL('../shared', import.meta.url));

/** Files the build writes that must never end up in the precache (the worker itself, Vite's own manifest). */
const SW_FILE = 'sw.js';
const SKIP_PRECACHE = new Set([SW_FILE, '.vite', 'manifest.json']);
/**
 * The owner's console (public/admin.html + public/admin/): never precached, and the worker lets every request
 * for it go straight to the network (ADMIN_PATH_RE in the worker below), so the owner always gets the current page.
 */
const isAdminFile = (f: string): boolean => f === 'admin.html' || f.startsWith('admin/');

/** Every file under `dir`, as `/`-separated paths relative to it (hidden entries skipped). */
function walk(dir: string, prefix = ''): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith('.')) continue;
    const abs = path.join(dir, entry);
    const rel = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(abs).isDirectory()) out.push(...walk(abs, rel));
    else out.push(rel);
  }
  return out;
}

const sha256 = (data: Buffer | string) => createHash('sha256').update(data).digest('hex');

/**
 * The service worker source. Relative paths only: the site lives under `/<repo>/` on GitHub Pages
 * and at `/` locally, so everything resolves against the registration scope (the folder of sw.js).
 *
 * Install: precache every emitted file (about 4 MB; hashed assets may come from the HTTP cache,
 * everything else is fetched fresh), then skipWaiting. Activate: drop this app's older caches and
 * claim the open pages. Fetch: navigations network-first with a 3 s timeout and the cached
 * index.html as the fallback; hashed `assets/*` cache-first; other same-origin GETs
 * stale-while-revalidate. Non-GET, cross-origin and out-of-scope requests are left alone (the
 * relay is a WebSocket and never passes through here anyway), and so is the owner's console
 * (admin.html, admin/…): it is not precached and always comes from the network.
 */
function serviceWorkerSource(precache: readonly string[], version: string): string {
  return `/* SquadHQ Racer service worker — generated by the build (game/vite.config.ts); do not edit. */
'use strict';
const VERSION = ${JSON.stringify(version)};
const CACHE_PREFIX = 'gf-racer-';
const CACHE = CACHE_PREFIX + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const NAV_TIMEOUT_MS = 3000;
/** The owner's console: network only (no cache, no index.html fallback). */
const ADMIN_PATH_RE = /^admin(?:\\.html)?(?:[/?#]|$)/;
const scope = self.registration.scope;
const toUrl = (p) => new URL(p, scope).href;
const INDEX_URL = toUrl('index.html');
const me = self.serviceWorker || null;

/** A newer worker has activated: this one must not write caches any more (it would re-create what the new one deleted). */
function superseded() {
  const active = self.registration.active;
  return !!(me && active && active !== me);
}

async function deleteOldCaches() {
  const keys = await caches.keys();
  await Promise.all(keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE).map((k) => caches.delete(k)));
}

async function broadcast(message) {
  const clients = await self.clients.matchAll({ includeUncontrolled: true, type: 'window' });
  for (const client of clients) client.postMessage(message);
}

async function precacheAll() {
  const cache = await caches.open(CACHE);
  await Promise.all(
    PRECACHE.map(async (p) => {
      const url = toUrl(p);
      // Hashed assets never change under the same name; everything else must bypass the HTTP cache.
      const request = new Request(url, { cache: p.startsWith('assets/') ? 'default' : 'reload', credentials: 'same-origin' });
      const response = await fetch(request);
      if (!response.ok) throw new Error('precache ' + p + ' -> HTTP ' + response.status);
      await cache.put(url, response);
    }),
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      await precacheAll();
      await self.skipWaiting();
      await broadcast({ type: 'gf:precached', version: VERSION, files: PRECACHE.length });
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      await deleteOldCaches();
      await self.clients.claim();
      // Again: a write the old worker had in flight may have re-created its cache meanwhile.
      await deleteOldCaches();
    })(),
  );
});

function withTimeout(promise, ms) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('timeout')), ms);
    promise.then(
      (v) => { clearTimeout(timer); resolve(v); },
      (e) => { clearTimeout(timer); reject(e); },
    );
  });
}

/** Navigations: the live page when the network answers within 3 s, else the precached index.html. */
async function navigate(request) {
  try {
    const response = await withTimeout(fetch(request.url, { cache: 'no-cache', credentials: 'same-origin' }), NAV_TIMEOUT_MS);
    if (response.status >= 500) throw new Error('HTTP ' + response.status);
    return response;
  } catch (error) {
    const cached = await caches.match(INDEX_URL);
    if (cached) {
      broadcast({ type: 'gf:offline', reason: String(error && error.message) });
      return cached;
    }
    throw error;
  }
}

/** Hashed assets: the cache has them; anything new (a lazy chunk of a newer build) is fetched and kept. */
async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok && !superseded()) {
    const cache = await caches.open(CACHE);
    cache.put(request, response.clone());
  }
  return response;
}

/** Manifest, icons, favicon: serve what we have, refresh it in the background. */
async function staleWhileRevalidate(event) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(event.request);
  const network = fetch(event.request)
    .then((response) => {
      if (response.ok && !superseded()) cache.put(event.request, response.clone());
      return response;
    })
    .catch(() => null);
  if (cached) {
    event.waitUntil(network);
    return cached;
  }
  const response = await network;
  if (response) return response;
  return Response.error();
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (!request.url.startsWith(scope)) return;
  const rel = request.url.slice(scope.length);
  // Not answered here: the browser fetches the console from the network as if there were no worker.
  if (ADMIN_PATH_RE.test(rel)) return;
  if (request.mode === 'navigate') {
    event.respondWith(navigate(request));
    return;
  }
  if (rel.startsWith('assets/')) {
    event.respondWith(cacheFirst(request));
    return;
  }
  event.respondWith(staleWhileRevalidate(event));
});

self.addEventListener('message', (event) => {
  const data = event.data || {};
  if (data.type === 'gf:status?') {
    event.waitUntil(
      (async () => {
        let cached = 0;
        try {
          const cache = await caches.open(CACHE);
          cached = (await cache.keys()).length;
        } catch {
          cached = 0;
        }
        const reply = { type: 'gf:status', version: VERSION, files: PRECACHE.length, cached, precached: cached >= PRECACHE.length };
        const port = event.ports && event.ports[0];
        if (port) port.postMessage(reply);
        else if (event.source) event.source.postMessage(reply);
      })(),
    );
  } else if (data.type === 'gf:skip-waiting') {
    self.skipWaiting();
  }
});
`;
}

/**
 * Writes `sw.js` next to index.html once the bundle is on disk: its precache list is every file
 * the build emitted (hashed assets, index.html, the manifest, icons, favicon) and its VERSION is a
 * hash of those files' contents, so any change in the build produces a byte-different worker and
 * the browser installs the update. Build only; the dev server never has a worker.
 */
function serviceWorkerPlugin(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'gamerfleet-service-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(resolved) {
      config = resolved;
    },
    writeBundle(options) {
      const outDir = options.dir ?? path.resolve(config.root, config.build.outDir);
      const files = walk(outDir)
        .filter((f) => !SKIP_PRECACHE.has(f) && !SKIP_PRECACHE.has(f.split('/')[0] ?? '') && !isAdminFile(f))
        .sort();
      if (!files.includes('index.html')) throw new Error('service worker: index.html missing from the build output');
      const digest = createHash('sha256');
      for (const f of files) digest.update(`${f}:${sha256(readFileSync(path.join(outDir, f)))}\n`);
      const version = digest.digest('hex').slice(0, 12);
      writeFileSync(path.join(outDir, SW_FILE), serviceWorkerSource(files, version));
      config.logger.info(`service worker: ${SW_FILE} v${version}, ${files.length} files precached`);
    },
  };
}

export default defineConfig({
  plugins: [react(), serviceWorkerPlugin()],
  resolve: {
    alias: { '@shared': sharedDir },
  },
  server: {
    host: true,
    // The wire protocol lives outside this package (../shared) and is imported as source.
    fs: { allow: ['.', sharedDir] },
  },
  preview: { host: true },
  build: {
    target: 'es2022',
    // Rapier ships its WASM inlined as base64 (~2 MB); it gets its own long-cacheable chunk.
    chunkSizeWarningLimit: 2600,
    rolldownOptions: {
      output: {
        codeSplitting: {
          groups: [
            { name: 'rapier', test: /node_modules[\\/]@dimforge/, priority: 3 },
            { name: 'three', test: /node_modules[\\/](three|three-stdlib|@react-three)[\\/]/, priority: 2 },
            { name: 'vendor', test: /node_modules/, priority: 1 },
          ],
        },
      },
    },
  },
});
