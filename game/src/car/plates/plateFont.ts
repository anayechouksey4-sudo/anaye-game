const BLANK = GLYPHS[' ']!;

/** The 7 row bitmasks of a character (unknown characters draw as a space). */
export function glyphRows(ch: string): readonly number[] {
  return GLYPHS[ch] ?? BLANK;
}

/** Every character the font can draw, for tests. */
export const GLYPH_CHARS: readonly string[] = Object.keys(GLYPHS);

/**
 * Paint `text` with `cell`-pixel squares: calls `dot(x, y, cell)` for every lit pixel, with the
 * glyph block's top-left at (x0, y0). Shared by the plate texture and the 2-D preview.
 */
export function layoutGlyphs(text: string, x0: number, y0: number, cell: number, dot: (x: number, y: number, size: number) => void): void {
  for (let c = 0; c < text.length; c++) {
    const rows = glyphRows(text[c]!);
    for (let r = 0; r < GLYPH_ROWS; r++) {
      const bits = rows[r] ?? 0;
      for (let b = 0; b < GLYPH_COLS; b++) if (bits & (1 << (GLYPH_COLS - 1 - b))) dot(x0 + (c * GLYPH_ADVANCE + b) * cell, y0 + r * cell, cell);
    }
  }
}

/** Width of `text` in cells (no trailing gap). */
export function textCells(text: string): number {
  return text.length === 0 ? 0 : text.length * GLYPH_ADVANCE - 1;
}
